"""scripts/tools/scale_scenarios.py

Generate the milliAmpere variants of the simulation scenarios
(scenarios/simulation/milliampere/) from the ship-scale ones.

milliAmpere's model is identified for speeds up to about 2 m/s, while the
ship-scale scenarios run ego at 2-6 m/s. Every length and speed is multiplied
by the same factor, so times (t = d / v) are unchanged: horizons, TCPA
thresholds and dt carry over as they are, and each encounter unfolds on the
same clock. Ego is switched to ``sim_model: milliampere`` with
``policy: predictor_dp`` (DP on a reference that follows the predictor's
forecast for ego), unless it is non-responsive: then it is a test vessel the
others must avoid and keeps its plain policy. Targets keep their kinematic
models and VO policies.

Scaled, besides the keys set in each file (speed, range, d_pass,
lateral_offset_m, viz.padding):
  * los_lookahead (VOAgentConfig default, set per vessel)
  * the overtaking start offset (encounter._OVERTAKING_LATERAL)
  * the COLREGs classifier distances d_u, dcpa_max, d_a (scenario.classifier)
  * the drawn hull size (viz.vessel.length/width)

Usage
-----
    python scripts/tools/scale_scenarios.py              # factor 0.3 (ego 5 -> 1.5 m/s)
    python scripts/tools/scale_scenarios.py --factor 0.25
"""

from __future__ import annotations

import argparse
import copy
from pathlib import Path

import yaml

from src.colregs_graph.colregs_classifier import ColregsClassifier
from src.prediction.vo_rollout import VOAgentConfig
from src.vessel.encounter import _OVERTAKING_LATERAL
from src.visualization.live_viz import VizConfig

REPO     = Path(__file__).resolve().parents[2]
SRC_DIR  = REPO / "scenarios/simulation"
OUT_DIR  = SRC_DIR / "milliampere"

_VESSEL_LENGTH_KEYS = ("speed", "range", "d_pass", "lateral_offset_m")


def scale_config(raw: dict, k: float) -> dict:
    def s(x: float) -> float:
        return round(float(x) * k, 3)

    out = copy.deepcopy(raw)
    sc  = out["scenario"]
    for vid, v in sc["vessels"].items():
        for key in _VESSEL_LENGTH_KEYS:
            if key in v:
                v[key] = s(v[key])
        if vid == "ego":
            v["sim_model"] = "milliampere"
            # A non-responsive ego is a test vessel the others must avoid, not
            # the ship under our control: it keeps its plain policy.
            if str(v.get("intent", "responsive")).lower() != "non_responsive":
                v["policy"] = "predictor_dp"
        if str(v.get("encounter", "")).startswith("overtaking") and "lateral_offset_m" not in v:
            v["lateral_offset_m"] = s(_OVERTAKING_LATERAL)
        v.setdefault("los_lookahead", s(VOAgentConfig.los_lookahead))

    clf = ColregsClassifier()
    sc["classifier"] = {"d_u": s(clf.d_u), "dcpa_max": s(clf.dcpa_max), "d_a": s(clf.d_a)}

    viz = out.setdefault("viz", {})
    if "padding" in viz:
        viz["padding"] = s(viz["padding"])
    viz_defaults = VizConfig()
    viz["vessel"] = {
        "length": s(viz_defaults.vessel_length),
        "width":  s(viz_defaults.vessel_width),
    }
    return out


def _header(name: str, k: float, ego_policy: str) -> str:
    rel_out = OUT_DIR.relative_to(REPO)
    if ego_policy == "predictor_dp":
        control = (
            f"# under dynamic positioning on a reference that steps along the predictor's\n"
            f"# forecast for ego (policy: predictor_dp; vo_analytic gives heading/speed\n"
            f"# control instead). Targets keep their kinematic models.\n"
        )
    else:
        control = (
            f"# under heading/speed control (policy: {ego_policy}). Ego is non-responsive\n"
            f"# here, a test vessel the others must avoid rather than the ship under our\n"
            f"# control, so it keeps its plain policy. Targets keep their kinematic models.\n"
        )
    return (
        f"# milliAmpere variant of ../{name}. GENERATED by scripts/tools/scale_scenarios.py\n"
        f"# -- edit the original and regenerate rather than editing this file.\n"
        f"#\n"
        f"# Every length and speed is scaled by {k:g}; time is unchanged, so the\n"
        f"# encounter unfolds on the same clock. Ego is simulated with the milliAmpere\n"
        f"# 3DOF model (sim_model: milliampere), identified for speeds up to ~2 m/s,\n"
        + control +
        f"#\n"
        f"# Run:\n"
        f"#   python scripts/run_simulation.py --config {rel_out}/{name}\n\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--factor", type=float, default=0.3,
                        help="length/speed scale factor (default 0.3: ego 5 -> 1.5 m/s)")
    args = parser.parse_args()

    OUT_DIR.mkdir(exist_ok=True)
    for src in sorted(SRC_DIR.glob("*.yaml")):
        scaled = scale_config(yaml.safe_load(src.read_text()), args.factor)
        body   = yaml.safe_dump(scaled, sort_keys=False, default_flow_style=False, width=100)
        dst    = OUT_DIR / src.name
        ego_policy = scaled["scenario"]["vessels"]["ego"]["policy"]
        dst.write_text(_header(src.name, args.factor, ego_policy) + body)
        print(f"wrote {dst.relative_to(REPO)}")


if __name__ == "__main__":
    main()
